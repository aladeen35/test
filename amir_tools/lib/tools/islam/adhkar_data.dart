/// نصوص الأذكار — منقولة بنصّها من القرآن الكريم والأحاديث المشهورة في كتب الأذكار.
/// تنبيه للمطوّر: لا تعدّل حرفًا في النصوص الدينية.
library;

class Dhikr {
  final String text;
  final int count;
  final String? title;
  final String? source;
  final String? note;
  const Dhikr(this.text, {this.count = 1, this.title, this.source, this.note});
}

class AdhkarSet {
  final String id, name, emoji, intro;
  final List<Dhikr> items;
  const AdhkarSet(this.id, this.name, this.emoji, this.intro, this.items);
  int get total => items.fold(0, (a, b) => a + b.count);
}

