/// عبارات التحية السودانية حسب الوقت
String sudaneseGreeting(int hour) {
  if (hour < 5) return 'سهران يا';
  if (hour < 12) return 'صباح الخير يا';
  if (hour < 16) return 'نهارك سعيد يا';
  if (hour < 19) return 'العصرية الحلوة يا';
  return 'مساء النور يا';
}
